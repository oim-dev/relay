import type { DocumentRelation } from "domains/documents";

/** Одна прямая связь материала, подготовленная к показу. */
export type RelationEntry = {
  /** Устойчивый адрес связи: вид, ID цели и тип. */
  address: string;
  /** Связь в форме контракта. */
  relation: DocumentRelation;
  /** Связь пришла из совместимой области links, а не из адресных relations. */
  isLegacy: boolean;
  /** Прежний адрес после миграции: карточки нет, связь только читается и снимается. */
  isRelocated: boolean;
  /** Название сущности или пояснение о её недоступности. */
  title: string;
  /** Публичный ключ сущности; null у прежнего адреса, где ключ входит в заголовок. */
  entityKey: string | null;
  /** Переход к сущности; null, если сущность не прочитана или это прежний адрес. */
  href: string | null;
  /** Переход к текущему владельцу прежнего адреса, например плану этапа. */
  owner: {
    /** Адрес экрана владельца. */
    href: string;
    /** Доступное имя перехода. */
    label: string;
  } | null;
};
