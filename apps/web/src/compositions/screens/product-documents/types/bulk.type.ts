/** Материал в множественном выборе каталога. */
export type SelectedMaterial = {
  /** Постоянный ID. */
  id: string;
  /** Ревизия, с которой материал выбран или которую сообщил сервер после отказа. */
  revision: number;
  /** Название для отчёта. */
  title: string;
  /** Теги на момент выбора: варианты для снятия. */
  tags: string[];
};
/** Неприменённый элемент массового действия. */
export type BulkRemainder = {
  /** Постоянный ID или адрес из запроса. */
  id: string;
  /** Название, если известно. */
  title: string;
  /** Исход элемента. */
  status: "conflict" | "not_found" | "invalid" | "error";
  /** Причина для человека. */
  reason: string;
};
/** Общие сведения о последнем массовом действии. */
type BulkOutcomeBase = {
  /** Описание действия. */
  action: string;
  /** Число выбранных материалов. */
  total: number;
  /** Сколько материалов это действие оставило выбранными. */
  kept: number;
};
/**
 * Фактический результат последнего массового действия:
 * квитанция с исходом каждого элемента, достоверный отказ всего запроса до применения
 * либо неизвестный исход, когда ответ о записи не получен.
 */
export type BulkOutcome =
  | (BulkOutcomeBase & {
      /** Сервер вернул квитанцию. */
      kind: "receipt";
      /** Сохранено. */
      applied: number;
      /** Без изменений: значение уже было таким. */
      unchanged: number;
      /** Не применено, с причинами. */
      remainder: BulkRemainder[];
    })
  | (BulkOutcomeBase & {
      /** Сервер ответил отказом всего запроса: ничего не применено. */
      kind: "rejected";
      /** Причина отказа от сервера. */
      message: string;
    })
  | (BulkOutcomeBase & {
      /** Ответ о записи не получен: изменения могли сохраниться. */
      kind: "unknown";
      /** Материалы, результат которых неизвестен. */
      items: { id: string; title: string }[];
    });
