/** Материал в множественном выборе каталога. */
export type SelectedMaterial = {
  /** Постоянный ID. */
  id: string;
  /** Ревизия, с которой материал выбран или которую сообщил сервер после отказа. */
  revision: number;
  /** Название для отчёта. */
  title: string;
  /** Теги на момент выбора: варианты для снятия. */
  tags: string[];
};
/** Неприменённый элемент массового действия. */
export type BulkRemainder = {
  /** Постоянный ID или адрес из запроса. */
  id: string;
  /** Название, если известно. */
  title: string;
  /** Исход элемента. */
  status: "conflict" | "not_found" | "invalid" | "error";
  /** Причина для человека. */
  reason: string;
};
/** Фактический результат последнего массового действия. */
export type BulkOutcome = {
  /** Описание действия. */
  action: string;
  /** Число выбранных материалов. */
  total: number;
  /** Сохранено. */
  applied: number;
  /** Без изменений: значение уже было таким. */
  unchanged: number;
  /** Не применено, с причинами. */
  remainder: BulkRemainder[];
  /** Отказ всего запроса; состояние неизвестно, требуется перечитать. */
  requestError: string | null;
};
