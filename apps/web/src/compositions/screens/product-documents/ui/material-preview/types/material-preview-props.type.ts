/** Быстрый предпросмотр материала каталога. */
export type MaterialPreviewProps = {
  /** Материал, показанный последним; сохраняется на время закрытия панели. */
  material: { id: string; title: string } | null;
  /** Панель открыта. */
  opened: boolean;
  /** Постоянный адрес полной карточки. */
  href: string;
  /** Адрес каталога для возврата из карточки. */
  returnTo: string;
  /** Закрытие панели с возвратом фокуса к вызвавшей кнопке. */
  onClose: () => void;
};
