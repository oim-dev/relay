/** Шапка каталога: название, поиск и создание материала. */
export type LibraryHeaderProps = {
  /** Введённая строка поиска. */
  query: string;
  /** Адрес создания материала в текущем разделе. */
  createHref: string;
  /** Адрес каталога для возврата из редактора. */
  returnTo: string;
  /** Изменение строки поиска. */
  onQueryChange: (query: string) => void;
  /** Открытие панели разделов на узком экране. */
  onOpenNavigation: () => void;
  /** Показ или скрытие фильтров: панель над выдачей, на телефоне — выдвижная панель. */
  onToggleFilters: () => void;
  /** Число активных фильтров из адреса для счётчика на кнопке. */
  filterCount: number;
  /** Фильтры сейчас показаны. */
  isFiltersExpanded: boolean;
  /** Идентификатор панели фильтров, которой управляет кнопка; нет у выдвижной панели. */
  filtersControls?: string;
};
