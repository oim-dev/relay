import type { Ref } from "react";

/** Ввод тегов материала с подсказками существующих тегов проекта. */
export type MaterialTagsInputProps = {
  /** Проект, теги которого предлагаются. */
  projectId: string;
  /** Выбранные теги. */
  value: string[];
  /** Нормализованный набор: без пустых и повторов без учёта регистра, не более 20. */
  onChange: (tags: string[]) => void;
  /** Подпись поля. */
  label?: string;
  /** Пояснение под подписью. */
  description?: string;
  /** Подсказка пустого поля. */
  placeholder?: string;
  /** Ошибка поля от владельца формы. */
  error?: string;
  /** Поле недоступно, например во время записи. */
  disabled?: boolean;
  /**
   * Собственный набор вариантов вместо всех тегов проекта, например теги выбранных материалов
   * для снятия. Новые теги тогда не создаются.
   */
  suggestions?: string[];
  /**
   * Список вариантов занимает место в форме под полем, а не всплывает поверх неё:
   * следующее действие формы остаётся видимым. По умолчанию список всплывает.
   */
  inlineOptions?: boolean;
  /** Поле — начальный фокус окна, в котором стоит (`data-autofocus` ловушки фокуса Mantine). */
  isDialogInitialFocus?: boolean;
  /**
   * Сообщает, можно ли зафиксировать текущий ввод тегом: ложь при слишком длинном теге
   * или, при собственном наборе вариантов, при теге вне набора. Пустой ввод допустим.
   */
  onDraftValidityChange?: (isValid: boolean) => void;
  /** Поле ввода: владелец формы возвращает в него фокус, например после ошибки. */
  ref?: Ref<HTMLInputElement>;
};
