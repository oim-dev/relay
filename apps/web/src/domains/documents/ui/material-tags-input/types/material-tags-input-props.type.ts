/** Ввод тегов материала с подсказками существующих тегов проекта. */
export type MaterialTagsInputProps = {
  /** Проект, теги которого предлагаются. */
  projectId: string;
  /** Выбранные теги. */
  value: string[];
  /** Нормализованный набор: без пустых и повторов без учёта регистра, не более 20. */
  onChange: (tags: string[]) => void;
  /** Подпись поля. */
  label?: string;
  /** Пояснение под подписью. */
  description?: string;
  /** Подсказка пустого поля. */
  placeholder?: string;
  /** Ошибка поля от владельца формы. */
  error?: string;
  /** Поле недоступно, например во время записи. */
  disabled?: boolean;
  /**
   * Собственный набор вариантов вместо всех тегов проекта, например теги выбранных материалов
   * для снятия. Новые теги тогда не создаются.
   */
  suggestions?: string[];
};
