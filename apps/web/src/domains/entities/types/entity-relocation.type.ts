/** Перенос прежнего адреса владельцу по сведениям Core (ENTITY_RELOCATED). */
export type EntityRelocation = {
  /** Прежний адрес вида `kind:id`. */
  from: string;
  /** Текущий владелец записи, например план прежнего этапа. */
  owner: {
    /** Вид владельца. */
    kind: string;
    /** Постоянный ID владельца. */
    id: string;
  };
  /** ID записи внутри владельца, например этапа плана. */
  stageId: string;
  /** Прежний публичный ключ записи; null, если ключа не было. */
  key: string | null;
};
